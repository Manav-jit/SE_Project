export async function advanceApplicationStatus(
  id: string,
  newStatus: ApplicationStatus,
  remark?: string
): Promise<ApplicationRecord | null> {
  const all = await getAllApplications();
  const index = all.findIndex(a => a.id.toLowerCase() === id.toLowerCase());
  if (index === -1) return null;

  const app = all[index];
  const now = new Date().toISOString();
  app.status = newStatus;
  app.updatedAt = now;

  // Advance tracking milestone status
  if (newStatus === 'UNDER_VERIFICATION') {
    app.trackingMilestones[1].status = 'COMPLETED';
    app.trackingMilestones[1].timestamp = now;
    if (remark) app.trackingMilestones[1].officerRemark = remark;
    if (app.trackingMilestones[2]) app.trackingMilestones[2].status = 'IN_PROGRESS';
  } else if (newStatus === 'FIELD_INSPECTION') {
    app.trackingMilestones[1].status = 'COMPLETED';
    if (app.trackingMilestones[2]) {
      app.trackingMilestones[2].status = 'COMPLETED';
      app.trackingMilestones[2].timestamp = now;
      if (remark) app.trackingMilestones[2].officerRemark = remark;
    }
    if (app.trackingMilestones[3]) app.trackingMilestones[3].status = 'IN_PROGRESS';
  } else if (newStatus === 'SANCTIONED') {
    app.trackingMilestones.forEach((m, idx) => {
      if (idx <= 3) {
        m.status = 'COMPLETED';
        if (!m.timestamp) m.timestamp = now;
      }
    });
    if (remark && app.trackingMilestones[3]) app.trackingMilestones[3].officerRemark = remark;
    if (app.trackingMilestones[4]) app.trackingMilestones[4].status = 'IN_PROGRESS';
  } else if (newStatus === 'DISBURSED') {
    app.trackingMilestones.forEach(m => {
      m.status = 'COMPLETED';
      if (!m.timestamp) m.timestamp = now;
    });
    if (remark && app.trackingMilestones[app.trackingMilestones.length - 1]) {
      app.trackingMilestones[app.trackingMilestones.length - 1].officerRemark = remark;
    }
  }

  all[index] = app;
  await fs.writeFile(APPLICATIONS_FILE, JSON.stringify(all, null, 2), 'utf-8');
  return app;
}
