async function ensureFileExists(): Promise<void> {
  try {
    await fs.access(APPLICATIONS_FILE);
  } catch {
    await fs.mkdir(path.dirname(APPLICATIONS_FILE), { recursive: true });
    await fs.writeFile(APPLICATIONS_FILE, JSON.stringify(INITIAL_SEED_APPLICATIONS, null, 2), 'utf-8');
  }
}

export async function getAllApplications(): Promise<ApplicationRecord[]> {
  await ensureFileExists();
  try {
    const raw = await fs.readFile(APPLICATIONS_FILE, 'utf-8');
    return JSON.parse(raw) as ApplicationRecord[];
  } catch (err) {
    console.error('Error reading applications file:', err);
    return INITIAL_SEED_APPLICATIONS;
  }
}

export async function getApplicationById(id: string): Promise<ApplicationRecord | null> {
  const all = await getAllApplications();
  return all.find(a => a.id.toLowerCase() === id.toLowerCase()) || null;
}

